// Generates src/styles/tokens.css from src/styles/tokens.ts (plan §7.2: one
// token file feeds both the CSS and the map style).
//   node scripts/build-tokens.mjs           write the CSS
//   node scripts/build-tokens.mjs --check   fail if the committed CSS is stale
import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { APP } from './lib.mjs';

const tokens = await import(
  pathToFileURL(path.join(APP, 'src/styles/tokens.ts')).href
);
const {
  COLOR,
  ERA_TINTS,
  WASHES,
  FONT,
  LAYOUT,
  TEXTBOOK_COLOR,
  TEXTBOOK_ERA_TINTS,
  TEXTBOOK_WASHES,
  TEXTBOOK_FONT,
  TEXTBOOK_LINE_STRONG,
  TEXTBOOK_MAP_ACCENT,
} = tokens;

const kebab = (s) => s.replace(/([a-z])([A-Z0-9])/g, '$1-$2').toLowerCase();
const lines = [];
const out = (s = '') => lines.push(s);

out(
  '/* Generated by scripts/build-tokens.mjs from src/styles/tokens.ts. Do not edit. */',
);
out(':root {');
// `light dark` on the root makes Safari 27.3's Adaptive Dark Mode skip the
// page (some builds ignore `light only`); `only` keeps Chrome's force-dark
// off. global.css pins everything inside <body> to `light only`, so nothing
// actually renders dark.
out('  color-scheme: light dark only;');
for (const [k, v] of Object.entries(COLOR)) out(`  --${kebab(k)}: ${v};`);
for (const [era, t] of Object.entries(ERA_TINTS)) {
  out(`  --era-${era}: ${t.ink};`);
  out(`  --era-${era}-wash: ${t.wash};`);
  out(`  --era-${era}-on-wash: ${t.onWash};`);
}
WASHES.forEach((w, i) => out(`  --wash-${i}: ${w.fill};`));
out(
  '  /* The UI accent is the era pigment of the map year (set on <html data-era>). */',
);
out('  --accent: var(--era-medieval);');
out('  --accent-wash: var(--era-medieval-wash);');
out('  --accent-on-wash: var(--era-medieval-on-wash);');
out(`  --font-serif: ${FONT.serif};`);
out(`  --font-sc: ${FONT.smallCaps};`);
out('  /* The year, titles and reading text; B sets Literata here. */');
out('  --font-display: var(--font-serif);');
out(`  --line-strong: ${COLOR.ink};`);
out(`  --map-accent: ${ERA_TINTS.medieval.ink};`);
out(`  --on-accent: ${COLOR.sheet};`);
out(`  --panel-width: ${LAYOUT.panelWidth}px;`);
out(`  --frame-inset: ${LAYOUT.frameInset}px;`);
out(
  '  /* Safe areas (§2.2). WebKit tests set --test-inset-* because env() cannot be injected. */',
);
for (const side of ['top', 'right', 'bottom', 'left'])
  out(
    `  --safe-${side}: max(env(safe-area-inset-${side}, 0px), var(--test-inset-${side}, 0px));`,
  );
out('}');
out();
for (const era of Object.keys(ERA_TINTS)) {
  out(`:root[data-era='${era}'] {`);
  out(`  --accent: var(--era-${era});`);
  out(`  --accent-wash: var(--era-${era}-wash);`);
  out(`  --accent-on-wash: var(--era-${era}-on-wash);`);
  out('}');
}
out();
out(
  '/* Direction B, "Modern textbook" (Settings → Map style), set on <html data-theme>. */',
);
out(":root[data-theme='textbook'] {");
for (const [k, v] of Object.entries(TEXTBOOK_COLOR))
  out(`  --${kebab(k)}: ${v};`);
for (const [era, t] of Object.entries(TEXTBOOK_ERA_TINTS)) {
  out(`  --era-${era}: ${t.ink};`);
  out(`  --era-${era}-wash: ${t.wash};`);
  out(`  --era-${era}-on-wash: ${t.onWash};`);
}
TEXTBOOK_WASHES.forEach((w, i) => out(`  --wash-${i}: ${w.fill};`));
out(`  --font-serif: ${TEXTBOOK_FONT.ui};`);
out(`  --font-sc: ${TEXTBOOK_FONT.ui};`);
out(`  --font-display: ${TEXTBOOK_FONT.display};`);
out(`  --line-strong: ${TEXTBOOK_LINE_STRONG};`);
out(`  --map-accent: ${TEXTBOOK_MAP_ACCENT};`);
out('  --on-accent: #FFFFFF;');
out('  /* No plate frame: the map runs to the edges of the stage. */');
out('  --frame-inset: 0px;');
out('}');
out();
out(
  '/* "Projector text" setting: Atkinson Hyperlegible Next for every UI string (after B, so it wins). */',
);
out(":root[data-text='projector'] {");
out(`  --font-serif: ${FONT.projector};`);
out(`  --font-sc: ${FONT.projector};`);
out(`  --font-display: ${FONT.projector};`);
out('}');
out();
out(`/* Breakpoints (not usable in @media; documented for CSS authors):
   phone <= ${LAYOUT.phoneMax}px, two-row header <= ${LAYOUT.twoRowMax}px,
   collapsed finder <= ${LAYOUT.finderCollapseMax}px. */`);

const css = `${lines.join('\n')}\n`;
const file = path.join(APP, 'src/styles/tokens.css');
if (process.argv.includes('--check')) {
  const current = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : '';
  if (current !== css) {
    console.error(
      'src/styles/tokens.css is stale: run `yarn remaster:tokens`.',
    );
    process.exit(1);
  }
  console.log('tokens.css is up to date');
} else {
  fs.writeFileSync(file, css);
  console.log(`wrote ${path.relative(APP, file)}`);
}
